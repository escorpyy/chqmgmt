const BS_EPOCH_AD = new Date(Date.UTC(1943, 3, 14)); // 1 Baishakh 2000 BS

export const BS_MONTHS = ['Baishakh','Jestha','Ashadh','Shrawan','Bhadra','Ashwin','Kartik','Mangsir','Poush','Magh','Falgun','Chaitra'];
export const BS_MONTHS_SHORT = ['Bai','Jes','Ash','Shr','Bha','Asw','Kar','Man','Pou','Mag','Fal','Cha'];

/** Number of days in a given BS month (0-based). Returns null if out of range. */
export function daysInBsMonth(year, month) {
  return BS_CALENDAR[year]?.[month] ?? null;
}

function toUtcMidnight(value) {
  const d = value instanceof Date ? value : new Date(value);
  if (isNaN(d.getTime())) return null;
  return new Date(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()));
}

/**
 * Convert an AD date (Date, ISO string, or anything `new Date()` accepts)
 * to its BS equivalent. Returns { year, month, day } (month is 0-based) or
 * null if it falls outside the supported range (BS 2000–2090).
 */
export function adToBs(value) {
  const adDate = toUtcMidnight(value);
  if (!adDate) return null;
  const diff = Math.floor((adDate.getTime() - BS_EPOCH_AD.getTime()) / 86400000);
  if (diff < 0) return null;
  let rem = diff;
  for (let y = 2000; y <= 2090; y++) {
    const months = BS_CALENDAR[y];
    if (!months) break;
    for (let m = 0; m < 12; m++) {
      if (rem < months[m]) return { year: y, month: m, day: rem + 1 };
      rem -= months[m];
    }
  }
  return null;
}

/**
 * Convert a BS date (year, 0-based month, day) to an AD Date (UTC midnight).
 * Returns null if the BS date is invalid or out of range.
 */
export function bsToAd(year, month, day) {
  if (!BS_CALENDAR[year] || month < 0 || month > 11) return null;
  if (day < 1 || day > BS_CALENDAR[year][month]) return null;
  let days = 0;
  for (let y = 2000; y < year; y++) {
    if (!BS_CALENDAR[y]) return null;
    days += BS_CALENDAR[y].reduce((a, b) => a + b, 0);
  }
  for (let m = 0; m < month; m++) days += BS_CALENDAR[year][m];
  days += day - 1;
  const result = new Date(BS_EPOCH_AD.getTime());
  result.setUTCDate(result.getUTCDate() + days);
  return result;
}

/**
 * "17 Bhadra 2083" — long-form BS date string for a given AD value.
 * Returns null if the date can't be converted (missing value or out of range).
 */
export function formatBsLong(value) {
  if (!value) return null;
  const bs = adToBs(value);
  if (!bs) return null;
  return `${bs.day} ${BS_MONTHS[bs.month]} ${bs.year}`;
}

/**
 * "2083-05-17" — BS date in ISO-ish YYYY-MM-DD form.
 */
export function formatBsIso(value) {
  if (!value) return null;
  const bs = adToBs(value);
  if (!bs) return null;
  const pad2 = (n) => String(n).padStart(2, '0');
  return `${bs.year}-${pad2(bs.month + 1)}-${pad2(bs.day)}`;
}
